#!/usr/bin/env python3
"""Fail when a dependency can enter the tree without an artifact hash.

The runtime and dev locks are compiled with ``uv pip compile --generate-hashes``
and installed with ``pip --require-hashes``.  That is only a guarantee while two
invariants hold:

* every line in ``requirements*.in`` is an exact ``name==version`` pin, so a
  fresh compile cannot silently pick up a newer release; and
* every pinned distribution in the compiled ``requirements*.txt`` carries at
  least one ``--hash=sha256:`` entry, so pip has an artifact digest to check.

This checker enforces both invariants and, crucially, the link between them: a
new direct pin in an ``.in`` file that was never compiled into the matching
lock is a failure.  It runs in CI as a blocking job and can be run locally with
``python ci-tooling/check_pinned_deps.py``.

No third-party imports: the gate must work in a bare ``python:3.14-slim``
container, before any dependency is installed.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# A direct pin: optional extras, then ``==``, then an exact (no wildcard) version.
PIN_RE = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)"
    r"(?:\[(?P<extras>[A-Za-z0-9._,\-]+)\])?"
    r"==(?P<version>[A-Za-z0-9][A-Za-z0-9._+!-]*)$",
)
HASH_RE = re.compile(r"^--hash=sha256:(?P<digest>[0-9a-f]{64})\s*\\?$")
PKG_RE = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)")
HEADER_RE = re.compile(r"autogenerated|generated by uv|uv pip compile", re.IGNORECASE)

# Directives that are legal in an .in file but are not dependencies.
IN_DIRECTIVES = {
    "-r",
    "-c",
    "--index-url",
    "--extra-index-url",
    "--find-links",
    "-e",
    "--editable",
}


def _distribution(name: str) -> str:
    """Normalise a distribution name the way PEP 503 does, for comparison."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _parse_in(path: Path, errors: list[str]) -> dict[str, str]:
    """Return the exact pins declared in an .in file."""
    pins: dict[str, str] = {}
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.split(maxsplit=1)[0] in IN_DIRECTIVES or line.startswith("-"):
            continue
        match = PIN_RE.match(line)
        if match is None:
            errors.append(
                f"{path}:{lineno}: unpinned requirement {line!r}; "
                "direct dependencies must use an exact 'name==version' pin"
            )
            continue
        key = _distribution(match.group("name"))
        if key in pins:
            errors.append(f"{path}:{lineno}: duplicate pin for {match.group('name')!r}")
        pins[key] = match.group("version")
    return pins


def _parse_lock(path: Path, errors: list[str]) -> dict[str, str]:
    """Return the pinned versions in a compiled lock, validating its hashes."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not any(HEADER_RE.search(line) for line in lines[:15]):
        errors.append(
            f"{path}: missing uv autogenerated header (compile with 'uv pip compile --generate-hashes')"
        )

    versions: dict[str, str] = {}
    current: tuple[str, int] | None = None
    current_hash = False
    saw_continuation = False

    def close_block() -> None:
        if current is not None and not current_hash:
            errors.append(
                f"{path}:{current[1]}: {current[0]} has no --hash=sha256 entry"
            )

    for lineno, raw in enumerate(lines, 1):
        stripped = raw.strip()
        pin = PKG_RE.match(raw)
        if pin and "==" in raw and not raw.startswith((" ", "#", "-")):
            close_block()
            name = pin.group("name")
            version = raw.split("==", 1)[1].split(";", 1)[0].split("\\", 1)[0].strip()
            current = (name, lineno)
            current_hash = False
            saw_continuation = raw.rstrip().endswith("\\")
            versions[_distribution(name)] = version
            continue
        if HASH_RE.match(stripped):
            if current is None:
                errors.append(f"{path}:{lineno}: --hash with no package above it")
                continue
            current_hash = True
            saw_continuation = stripped.endswith("\\")
            continue
        if stripped.startswith("# via"):
            saw_continuation = False
        elif saw_continuation and stripped and not stripped.startswith("#"):
            errors.append(
                f"{path}:{lineno}: unexpected line inside a hash block: {stripped!r}"
            )
            saw_continuation = stripped.endswith("\\")
    close_block()
    return versions


def check(repo: Path) -> list[str]:
    """Run every pinning invariant and return the human-readable failures."""
    errors: list[str] = []
    for source_name, lock_name in (
        ("requirements.in", "requirements.txt"),
        ("requirements-dev.in", "requirements-dev.txt"),
    ):
        source = repo / source_name
        lock = repo / lock_name
        if not source.is_file():
            errors.append(f"{source}: missing input pin file")
            continue
        if not lock.is_file():
            errors.append(f"{lock}: missing compiled lock")
            continue
        pins = _parse_in(source, errors)
        versions = _parse_lock(lock, errors)
        for name, version in pins.items():
            if name not in versions:
                errors.append(
                    f"{source_name}: {name}=={version} is declared but absent from {lock_name}; "
                    "recompile the lock with 'uv pip compile --generate-hashes'"
                )
            elif versions[name] != version:
                errors.append(
                    f"{source_name}: {name} is pinned to {version} but {lock_name} resolves {versions[name]}; "
                    "recompile the lock"
                )
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo", type=Path, default=Path.cwd(), help="repository root (default: cwd)"
    )
    args = parser.parse_args(argv)

    errors = check(args.repo.resolve())
    if errors:
        print("FAIL: dependency pinning invariant violated", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    print("dependency pinning OK: exact .in pins, every lock entry hashed and in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
