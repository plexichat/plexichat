#!/usr/bin/env python3
"""Regression tests for the supply-chain gates.

Each gate has two sides: it must pass on the real tree, and it must fail on a
synthetic tree that reintroduces the weakness it exists to catch. These tests
exercise both, so a deleted gate, a weakened check or a widened permission
shows up as a red CI job instead of a silent policy regression.

Run with: python ci-tooling/test_supply_chain.py
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SCRIPTS = {
    "pins": HERE / "check_pinned_deps.py",
    "secrets": HERE / "check_secrets_baseline.py",
    "permissions": HERE / "check_ci_permissions.py",
    "checksums": HERE / "check_artifact_checksums.py",
}


def run(script: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(script), *args],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=False,
    )


class SupplyChainGates(unittest.TestCase):
    """The real tree must satisfy every gate."""

    def test_pins_pass_on_real_tree(self) -> None:
        result = run(SCRIPTS["pins"], "--repo", str(REPO))
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_secrets_pass_on_real_tree(self) -> None:
        result = run(SCRIPTS["secrets"], "--root", str(REPO))
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_permissions_pass_on_real_tree(self) -> None:
        result = run(SCRIPTS["permissions"], "--repo", str(REPO))
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_checksums_pass_on_real_tree(self) -> None:
        result = run(SCRIPTS["checksums"], "--repo", str(REPO))
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_every_gate_is_wired_into_ci(self) -> None:
        ci = (REPO / ".gitlab-ci.yml").read_text(encoding="utf-8")
        for name, script in SCRIPTS.items():
            self.assertIn(
                script.name, ci, f"{name} gate is no longer invoked by the pipeline"
            )
            self.assertIn(
                "allow_failure: false", ci, "a supply-chain gate must be blocking"
            )

    def test_policy_audiences_are_bounded(self) -> None:
        policy = json.loads(
            (HERE / "ci-permissions-policy.json").read_text(encoding="utf-8")
        )
        self.assertTrue(policy["required_aud"], "OIDC tokens need a declared audience")
        for job, vars_ in policy["var_allowlist"].items():
            for var in vars_:
                self.assertIn(
                    var,
                    policy["privileged_vars"],
                    f"{job} grants unknown variable {var}",
                )


class RegressionFixtures(unittest.TestCase):
    """Synthetic regressions must fail the matching gate."""

    def test_unpinned_requirement_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "requirements.in").write_text("requests>=2.0\n", encoding="utf-8")
            (root / "requirements.txt").write_text(
                "# autogenerated by uv\n", encoding="utf-8"
            )
            result = run(SCRIPTS["pins"], "--repo", str(root))
            self.assertNotEqual(result.returncode, 0, "a range pin must fail the gate")
            self.assertIn("unpinned requirement", result.stderr)

    def test_hashed_lock_without_header_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "requirements.in").write_text("requests==2.0.0\n", encoding="utf-8")
            (root / "requirements.txt").write_text(
                "requests==2.0.0 \\\n    --hash=sha256:" + "a" * 64 + "\n",
                encoding="utf-8",
            )
            result = run(SCRIPTS["pins"], "--repo", str(root))
            self.assertNotEqual(
                result.returncode, 0, "a lock without a uv header must fail"
            )

    def test_new_token_without_baseline_entry_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".secrets.baseline").write_text(
                '{"results": {}}\n', encoding="utf-8"
            )
            token = "AKIA" + "A" * 16
            (root / "token.py").write_text(f'AWS_KEY = "{token}"\n', encoding="utf-8")
            result = run(SCRIPTS["secrets"], "--root", str(root))
            self.assertNotEqual(result.returncode, 0, "a new token must fail the gate")
            self.assertIn("not in .secrets.baseline", result.stderr)

            baseline = {
                "results": {
                    "token.py": [
                        {
                            "type": "AWSKeyDetector",
                            "filename": "token.py",
                            "hashed_secret": hashlib.sha1(
                                token.encode("utf-8")
                            ).hexdigest(),
                            "is_verified": False,
                            "line_number": 1,
                        },
                    ],
                },
            }
            (root / ".secrets.baseline").write_text(
                json.dumps(baseline), encoding="utf-8"
            )
            result = run(SCRIPTS["secrets"], "--root", str(root))
            self.assertEqual(
                result.returncode, 0, "a baselined token must pass: " + result.stderr
            )

    def test_widened_token_scope_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".gitlab-ci.yml").write_text(
                "stages:\n  - test\n"
                "evil:\n  stage: test\n  script:\n"
                '    - echo "$PLEXICHAT_MR_PAT"\n',
                encoding="utf-8",
            )
            result = run(
                SCRIPTS["permissions"], "--repo", str(root), "--ci", ".gitlab-ci.yml"
            )
            self.assertNotEqual(result.returncode, 0, "a new PAT consumer must fail")
            self.assertIn("privileged variable", result.stderr)

    def test_unbounded_id_token_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".gitlab-ci.yml").write_text(
                "stages:\n  - test\n"
                "oidc:\n  stage: test\n  id_tokens:\n    TOKEN:\n"
                "      aud: https://elsewhere.example\n  script:\n    - true\n",
                encoding="utf-8",
            )
            result = run(
                SCRIPTS["permissions"], "--repo", str(root), "--ci", ".gitlab-ci.yml"
            )
            self.assertNotEqual(
                result.returncode, 0, "an out-of-policy audience must fail"
            )

    def test_unhashed_pip_install_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".gitlab-ci.yml").write_text(
                "stages:\n  - test\n"
                "install:\n  stage: test\n  script:\n"
                "    - pip install -r requirements.txt\n",
                encoding="utf-8",
            )
            result = run(
                SCRIPTS["checksums"], "--repo", str(root), "--ci", ".gitlab-ci.yml"
            )
            self.assertNotEqual(
                result.returncode, 0, "an unpinned pip install must fail"
            )
            self.assertIn("--require-hashes", result.stderr)

    def test_unverified_download_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / ".gitlab-ci.yml").write_text(
                "stages:\n  - test\n"
                "download:\n  stage: test\n  script:\n"
                "    - curl -sSLo tool.sh https://example.invalid/tool.sh\n"
                "    - sh tool.sh\n",
                encoding="utf-8",
            )
            result = run(
                SCRIPTS["checksums"], "--repo", str(root), "--ci", ".gitlab-ci.yml"
            )
            self.assertNotEqual(result.returncode, 0, "an unchecked download must fail")

    def test_checksum_sidecar_mismatch_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "artifact.bin").write_bytes(b"good bytes")
            (root / "artifact.bin.sha256").write_text(
                "0" * 64 + "  artifact.bin\n", encoding="utf-8"
            )
            result = run(
                SCRIPTS["checksums"], "--repo", str(root), "--ci", "missing.yml"
            )
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("sha256 mismatch", result.stderr)


if __name__ == "__main__":
    unittest.main(verbosity=2)
