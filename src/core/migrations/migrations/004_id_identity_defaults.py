"""
Migration 004: give PostgreSQL ``id`` primary keys an identity default.

The canonical schema is authored in SQLite dialect, where a bare
``INTEGER PRIMARY KEY`` is the rowid alias: SQLite assigns an id when an insert
omits the column. That schema is converted for PostgreSQL by
``Database.convert_schema``, and until now only ``INTEGER PRIMARY KEY
AUTOINCREMENT`` was rewritten to an identity column. A bare ``INTEGER PRIMARY
KEY`` became ``BIGINT PRIMARY KEY``, which has no default, so every insert that
let SQLite pick the id failed:

* ``admin_audit_log`` -- admin audit writes were lost on every PostgreSQL
  install (the logger catches the failure and warns),
* ``msg_attachments`` -- attaching a file to a message failed,
* ``username_blacklist`` -- reserving a username raised instead of inserting.

``convert_schema`` now emits ``GENERATED BY DEFAULT AS IDENTITY`` for that
shape, which fixes new installs. This migration repairs existing databases: it
finds the ``id`` primary-key columns that have neither an identity nor a
default, and adds an identity to each. ``GENERATED BY DEFAULT`` means explicit
ids (snowflakes, backfills) keep working unchanged.
"""

import logging
import re

logger = logging.getLogger(__name__)

# Table and column names come back from the catalogue, but they are still
# interpolated into DDL below, so only plain identifiers are accepted.
_IDENTIFIER = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_]*$")

# Single-column integer ``id`` primary keys with neither an identity nor a
# default. Composite primary keys, text ids and other column names are out of
# scope: the codebase only relies on SQLite auto-assigning the column literally
# named ``id``.
_MISSING_IDENTITY = """
SELECT c.table_name AS table_name
FROM information_schema.columns c
JOIN information_schema.table_constraints tc
  ON tc.table_schema = c.table_schema
 AND tc.table_name = c.table_name
 AND tc.constraint_type = 'PRIMARY KEY'
JOIN information_schema.key_column_usage k
  ON k.constraint_schema = tc.constraint_schema
 AND k.constraint_name = tc.constraint_name
 AND k.table_name = c.table_name
 AND k.column_name = c.column_name
WHERE c.table_schema = 'public'
  AND c.column_name = 'id'
  AND c.is_identity = 'NO'
  AND c.column_default IS NULL
  -- Identity only exists for integer types: some tables key on a text id
  -- (media_upload_sessions, search_categories) and must be left alone.
  AND c.data_type IN ('bigint', 'integer', 'smallint')
ORDER BY c.table_name
"""


def _missing_identity_tables(db) -> list:
    """Return the tables whose ``id`` primary key assigns nothing itself."""
    rows = db.fetch_all(_MISSING_IDENTITY) or []
    tables = []
    for row in rows:
        name = row["table_name"] if isinstance(row, dict) else row[0]
        if name and _IDENTIFIER.match(str(name)):
            tables.append(str(name))
    return tables


def up(db):
    """Add an identity to every ``id`` primary key that lacks one."""
    if db.type != "postgres":
        return
    tables = _missing_identity_tables(db)
    if not tables:
        logger.info("Migration 004: every id primary key already assigns ids")
        return
    repaired = 0
    for table in tables:
        try:
            db.execute(
                f'ALTER TABLE "{table}" ALTER COLUMN id '
                "ADD GENERATED BY DEFAULT AS IDENTITY"
            )
            repaired += 1
        except Exception as e:  # pragma: no cover - defensive
            # A concurrent migration may have added the identity already;
            # anything else has to surface, because the table stays broken.
            if "already has an identity" in str(e).lower():
                continue
            raise
    logger.info(
        "Migration 004: added an identity to %d of %d id primary key(s)",
        repaired,
        len(tables),
    )


def down(db):
    """No-op: removing the identity would re-break inserts that omit ids."""
    logger.info("Migration 004 rollback: identities are left in place")
