"""Real-server e2e for the screen-share guard under production wiring.

``server/initializer.py`` hands ``signaling.setup(voice_module=...)`` the
``src.core.voice`` **module**. Every pre-existing voice test instead wires the
*manager instance* from ``server_with_voice`` -- which is exactly why the
guard's fail-open survived: ``getattr(module, "_require_permission")`` returned
``None``, so ``_require_stream_permission`` skipped ``voice.speak`` under the
only wiring production actually uses.

These tests wire the module, build real membership, real channel overrides and
the real ``VoiceManager``, then assert the guard denies. Only the plan-level
side effects (SFU/network) are avoided by using the ``aiortc`` backend with an
unreachable STUN host -- no traffic is generated by these calls.
"""

from __future__ import annotations

import asyncio
from types import SimpleNamespace

import pytest

import src.core.voice as voice
import src.core.voice.signaling as signaling
from src.core.voice.exceptions import PermissionDeniedError


def _voice_state_row(db, user_id: int):
    return db.fetch_one("SELECT * FROM voice_states WHERE user_id = ?", (user_id,))


@pytest.fixture
def screenshare(
    db,
    auth_manager,
    server_manager,
    rel_manager,
    presence_manager,
    three_users,
):
    """A real server whose owner/member may speak; the third user is an outsider."""
    owner, member, outsider = three_users

    server = server_manager.create_server(owner.id, "Screen-share E2E server")
    server_manager.add_member(server.id, member.id)
    voice_channel = server_manager.create_channel(
        owner.id, server.id, "voice-chat", channel_type=server_manager.ChannelType.VOICE
    )

    # Production wiring: the MODULE facade, not a manager instance.
    voice.setup(
        db,
        auth_module=auth_manager,
        servers_module=server_manager,
        relationships_module=rel_manager,
        presence_module=presence_manager,
    )
    signaling.setup(
        voice_module=voice,
        events_module=None,
        sfu_backend="aiortc",
        stun_urls=["stun:stun.example.invalid:3478"],
        turn_urls=[],
        turn_secret="",
        turn_ttl=3600,
    )

    try:
        yield SimpleNamespace(
            owner=owner,
            member=member,
            outsider=outsider,
            server=server,
            voice_channel=voice_channel,
            servers=server_manager,
            manager=signaling._get_manager(),
            db=db,
        )
    finally:
        for user in (owner, member, outsider):
            try:
                if voice.is_user_in_voice(user.id):
                    voice.leave_channel(user.id)
            except Exception:
                pass
        try:
            asyncio.run(signaling.close())
        except Exception:
            pass
        signaling._manager = None
        signaling._setup_complete = False
        voice._manager = None
        voice._setup_complete = False


def _deny_speak(ctx, channel) -> None:
    """Deny ``voice.speak`` for the default role on ``channel``."""
    everyone_role = next(
        role
        for role in ctx.servers.get_roles(ctx.owner.id, ctx.server.id)
        if role.is_default
    )
    ctx.servers.set_channel_override(
        ctx.owner.id,
        int(channel.id),
        "role",
        everyone_role.id,
        deny={"voice.speak": True},
    )


# === The fix itself =========================================================


def test_module_wiring_resolves_to_the_real_voice_manager(screenshare):
    """The accessor that makes the guard run at all.

    Before the fix the guards did ``getattr(module, "_require_permission")``,
    which is ``None`` on the module, so the ``voice.connect`` / ``voice.speak``
    checks were skipped. The accessor must resolve the module facade to the
    concrete manager.
    """
    assert screenshare.manager._voice_manager() is voice._get_manager()


# === Non-member =============================================================


def test_non_member_cannot_open_a_voice_connection(screenshare):
    """A genuine non-member is denied at connect, before any screen share."""
    with pytest.raises(PermissionDeniedError):
        signaling.create_voice_connection(
            screenshare.outsider.id, int(screenshare.voice_channel.id)
        )

    # No signaling connection and no persisted voice state were created.
    assert screenshare.manager._connections.get(screenshare.outsider.id) is None
    assert _voice_state_row(screenshare.db, screenshare.outsider.id) is None


def test_non_member_cannot_start_a_screen_share(screenshare):
    """Without a connection the share cannot start; the outsider gets nothing."""
    with pytest.raises(Exception):
        signaling.start_screen_share(
            screenshare.outsider.id, int(screenshare.voice_channel.id)
        )

    assert screenshare.manager._connections.get(screenshare.outsider.id) is None
    assert _voice_state_row(screenshare.db, screenshare.outsider.id) is None


# === Member without voice.speak =============================================


def test_speak_denied_member_is_refused_and_writes_nothing(screenshare, monkeypatch):
    """The guard the fail-open skipped: a member who may connect but not speak.

    ``create_voice_connection`` only enforces ``voice.connect``, so this member
    legitimately obtains a signaling connection -- and must still be refused a
    screen share, with no streaming state written.
    """
    _deny_speak(screenshare, screenshare.voice_channel)

    signaling.create_voice_connection(
        screenshare.member.id, int(screenshare.voice_channel.id)
    )

    streaming_calls: list[tuple] = []
    monkeypatch.setattr(
        voice, "set_streaming", lambda *args, **kwargs: streaming_calls.append(args)
    )

    with pytest.raises(PermissionDeniedError):
        signaling.start_screen_share(
            screenshare.member.id, int(screenshare.voice_channel.id)
        )

    connection = screenshare.manager._connections[screenshare.member.id]
    assert connection.screen_share is None
    assert streaming_calls == []
    row = _voice_state_row(screenshare.db, screenshare.member.id)
    assert row is None or not row["streaming"]


def test_start_works_for_a_member_who_may_speak(screenshare):
    """Complement: the same path succeeds without the deny, so the refusal
    above is authorization-specific rather than a blanket failure."""
    voice.join_channel(screenshare.member.id, int(screenshare.voice_channel.id))
    signaling.create_voice_connection(
        screenshare.member.id, int(screenshare.voice_channel.id)
    )

    state = signaling.start_screen_share(
        screenshare.member.id, int(screenshare.voice_channel.id)
    )

    assert state.active is True
    connection = screenshare.manager._connections[screenshare.member.id]
    assert connection.screen_share is not None
    assert connection.screen_share.active is True
    row = _voice_state_row(screenshare.db, screenshare.member.id)
    assert row is not None and row["streaming"]


def test_speak_denied_member_may_still_join_the_channel(screenshare):
    """The denial is specifically ``voice.speak``: the member still connects.

    ``create_voice_connection`` (``voice.connect``) succeeds for this member,
    which is what makes the screen-share refusal meaningful.
    """
    _deny_speak(screenshare, screenshare.voice_channel)

    info = signaling.create_voice_connection(
        screenshare.member.id, int(screenshare.voice_channel.id)
    )

    assert info is not None
    assert screenshare.manager._connections.get(screenshare.member.id) is not None
